/**
 * Generates 6 weeks (42 days) of realistic daily biometric logs
 */
export function generateSeedBiometrics(): BiometricLog[] {
  const logs: BiometricLog[] = [];
  const baseDate = new Date();
  baseDate.setDate(baseDate.getDate() - 42); // 42 days ago

  let currentWeight = 81.6;
  const targetWeight = 83.2; // slight lean bulk over 6 weeks

  for (let i = 0; i <= 42; i++) {
    const d = new Date(baseDate);
    d.setDate(d.getDate() + i);
    const dateStr = d.toISOString().split('T')[0];

    // Gradual progression with natural day-to-day noise
    const progressFrac = i / 42;
    const noise = (Math.sin(i * 1.7) * 0.35) + ((i % 5 === 0) ? 0.4 : -0.2);
    currentWeight = 81.6 + (targetWeight - 81.6) * progressFrac + noise;

    // Biometrics with realistic correlations:
    // Some days with slight dips for Amber Shield simulation
    const isDipDay = i === 12 || i === 26 || i === 41; // 41 is yesterday or close
    const hrv = isDipDay ? 42 + Math.floor(Math.random() * 4) : 56 + Math.floor(Math.sin(i * 0.8) * 9);
    const rhr = isDipDay ? 63 : 55 + Math.floor(Math.cos(i * 0.5) * 4);
    const sleep = isDipDay ? 5.4 : 7.2 + Math.sin(i * 0.4) * 0.9;
    const steps = 8500 + Math.floor(Math.sin(i * 1.2) * 2800) + (i % 3 === 0 ? 1500 : 0);
    const azm = 32 + Math.floor(Math.sin(i * 0.9) * 22) + (i % 2 === 0 ? 18 : 0);
    const vo2Max = 44.5 + Math.round((progressFrac * 1.8) * 10) / 10;

    logs.push({
      date: dateStr,
      bodyweightKg: Math.round(currentWeight * 10) / 10,
      hrvRmssd: Math.max(35, hrv),
      restingHr: rhr,
      sleepHours: Math.round(sleep * 10) / 10,
      steps: Math.max(4500, steps),
      activeZoneMinutes: Math.max(15, azm),
      vo2Max,
      avgWorkoutHr: 138 + Math.floor(Math.sin(i) * 8),
      workoutDurationMin: 62 + (i % 4) * 3,
    });
  }

  return logs;
}

